    public class CurrencyPerformanceService_GetDistributionWithComparison_Test : CurrencyPerformanceServiceTestBase
    {
        [Fact]
        public async Task GetDistributionWithComparison_WhenCall_MapperShouldCallCorrectParams()
        {
            //Arrange
            var filter = FakeCurrencyPerformanceFilterMetaModel;
            var data = new List<IEnumerable<CurrencyDistributionDTO>> { _fixture.CreateMany<CurrencyDistributionDTO>(), _fixture.CreateMany<CurrencyDistributionDTO>() };

            _repositoryMock.Setup(_ => _.QueryMultipleAsync<CurrencyDistributionDTO>(It.IsAny<ICriteria>(), It.IsAny<ICriteria>()))
                .ReturnsAsync(data);

            //Act
            await _target.GetDistributionWithComparison(filter);

            //Assert
            _mapperMock.Verify(_ => _.ToDistributionVM(data[0], data[1], It.IsAny<IEnumerable<DistributionMetaModel>>()), Times.Once);
        }

        [Fact]
        public async Task GetDistributionWithComparison_WhenCall_ServiceResultIsMapperResult()
        {
            //Arrange
            var filter = FakeCurrencyPerformanceFilterMetaModel;
            var expected = _fixture.CreateMany<DistributionVM>();

            _mapperMock.Setup(_ => _.ToDistributionVM(It.IsAny<IEnumerable<CurrencyDistributionDTO>>(), It.IsAny<IEnumerable<CurrencyDistributionDTO>>(), It.IsAny<IEnumerable<DistributionMetaModel>>()))
                .Returns(expected);

            //Act
            var result = await _target.GetDistributionWithComparison(filter);

            //Assert
            Assert.Equal(expected, result);
        }
